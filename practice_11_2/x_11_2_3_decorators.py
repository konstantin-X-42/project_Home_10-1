from time import time


def my_decorator(func):  # type: ignore
    def wrapper():  # type: ignore
        print("Исполнения кода перед вызовом функции.")
        func()  # Вызов исходной функции
        print("Исполнение кода после вызова функции.")

    return wrapper  # возвращает ссылку на функцию


print("\n-- my_decorator(func) --")


@my_decorator
def say_hello():  # type: ignore # запускаем декоратор, имя декоратора произвольное
    print("Hello!")


say_hello()

