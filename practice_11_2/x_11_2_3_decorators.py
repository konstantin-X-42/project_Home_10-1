"""
Задача c видео урока
Написать декоратор, который фиксирует время начала работы функции и время окончания ее работы.

Флоу решения:
1. Написать функцию-декоратор, которая создает и возвращает функцию-обертку.
2. Обертка должна фиксировать время до и после выполнения функции и выводить разницу.
3. Применить декоратор к функции.
"""


# --------------------------------------------
# при вызове функции декоратор работает, но ничего не меняет функция вернет значения своего алгоритма
def timer_1(func):  # type: ignore
    """декоратор не меняет работу функции"""

    def wrapper(*args, **kwargs):  # type: ignore
        result = func(*args, **kwargs)
        return result

    return wrapper


# --------------------------------------------


def timer(func):  # type: ignore         # оборачиваем функцию "func" в декоратор "timer"
    """функция декоратор выводит время работы функции"""

    def wrapper(*args, **kwargs):  # type: ignore  # передаём аргументы из функции "func" функцию "wrapper"
        time_1 = time()  # обращаемся к библиотеке time функция time() начальное время
        result = func(*args, **kwargs)  # запускаем код функции с аргументами "func" переданной в декоратор
        time_2 = time()  # фиксируем время завершения работы функции "func"
        print(f"Время работы функции: {time_2 - time_1}")  # выводим в консоль времени работы "func"
        return result  # возвращает результат функции "func"

    return wrapper  # возвращает ссылку на функцию


print("\n-- timer(func) --")


@timer
def example():  # type: ignore
    for i in range(100000000):  # задаем время для "торможение ПК" при переборе
        # искусственно замедляем исполнение функции "func"
        continue  # продолжает работу


if __name__ == "__main__":
    example()  # вызываем функцию декоратор

