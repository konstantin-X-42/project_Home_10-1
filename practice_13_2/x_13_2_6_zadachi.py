"""
Вам дана строка:
text = 'Цвет неба - синий.'
Напишите и примените регулярное выражение, чтобы заменить все вхождения слова синий на слово blue
"""
# import re

text = "Цвет неба - синий."
new_text = re.sub(r"синий", "blue", text)
print(new_text)

# >>> Цвет неба - blue.

# передаем два аргумента методу  sub()   шаблон регулярного выражения для поиска (r'синий')
# и строку замены   ('blue')  . Метод   sub()    возвращает новую строку с заменой всех вхождений
# шаблона на строку замены.
