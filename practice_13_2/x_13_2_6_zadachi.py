"""
У вас есть текст сообщения:
text = 'Позвоните мне по номеру 555-123-4567 или 555-987-6543'
Напишите и примените регулярное выражение, чтобы извлечь номера телефонов,
т. е. найти любую последовательность из 10 цифр, которая может представлять собой номер телефона.
"""
# import re

text = "Позвоните мне по номеру 555-123-4567 или 555-987-6543"

pattern = re.compile(r"\d{3}-\d{3}-\d{4}")
phone_numbers = pattern.findall(text)
print(phone_numbers)

# >>> ['555-123-4567', '555-987-6543']

# Регулярное выражение
# \d{3}-\d{3}-\d{4} соответствует любой последовательности из 10 цифр, разделенных дефисами.


