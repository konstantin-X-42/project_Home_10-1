# from collections import deque


def add_customer(my_queue, customer):  # type: ignore
    """добавляем клиентов по очереди в право"""
    my_queue.append(customer)
    print(f"Текущее состояние очереди: {my_queue}")


def add_vip_customer(my_queue, customer):  # type: ignore
    """добавляем VIP клиентов к основной очереди в лево"""
    my_queue.appendleft(customer)
    print(f"Текущее состояние очереди: {my_queue}")


def surve_customer(my_queue):  # type: ignore
    """обслуживание клиентов с приоритетом VIP затем остальные"""
    if my_queue:
        print(f"Обслуживаем клиента: {my_queue.popleft()}")
    else:
        print("Очередь пуста")
    print(f"Текущее состояние очереди: {my_queue}")


