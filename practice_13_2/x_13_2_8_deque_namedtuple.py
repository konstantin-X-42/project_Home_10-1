"""
namedtuple — фабрика для создания именованных кортежей.
Именованный кортеж — это кортеж, который позволяет обращаться к элементам по имени, что делает код более читаемым.
"""

# from collections import namedtuple

# Создание класса Point
Point = namedtuple("Point", ["x", "y"])

# Создание объекта Point
p = Point(1, 2)

# Вывод значений
print(p.x, p.y)


"""
Методы namedtuple_replace(**kwargs) — возвращает новый объект с замененными полями.
_asdict() — возвращает OrderedDict, представляющий кортеж.
_fields — возвращает список с именами полей.
_make(iterable) — создает namedtuple из итерируемого объекта.
"""


# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --
print("\n--  --  11. МЕТОДЫ и СВОЙСТВА создание класса Point --  --  --\n")
# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --

Point = namedtuple("Point", ["x", "y"])  # type: ignore
# Создание объекта Point
p = Point(1, 2)
print(p.x, p.y)


# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --
print("\n--  --  12. Замена значения поля  --  --  --\n")
# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --
# ._replace(...) — метод, который берет за основу данные из p, копирует их, но заменяет указанные поля.
p2 = p._replace(x=10)
print(p2)


# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --
print("\n--  --  13. Преобразование в словарь  --  --  --\n")
# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --

# ._asdict() — метод, превращает именованный кортеж p в обычный словарь
print(p._asdict())


# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --
print("\n--  --  14. Список полей --  --  --\n")
# --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --  --

# ._fields — специальное свойство (кортеж), в котором хранятся только названия колонок (полей), без самих данных.
