"""
Задача
Найти все цены в строке и вернуть их в виде списка.Цены могут быть указаны в различных валютах
(например, $, €, £) и должны состоять из целой и дробной части, разделенных точкой.
Пример строки:
The prices are $100.50, €200.75, and £300.99.
"""

# import re

# Пример строки с ценами
text = "The prices are $100.50, €200.75, and £300.99."

