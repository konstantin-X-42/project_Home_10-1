"""
Библиотека re
"""

import re

# Поиск всех цен в строке
text = "The price of the product is $100.50"
numbers = re.findall(r"\d+\.\d+", text)
print(numbers)

# >>> ['100.50']

# re.findall() ищет все совпадения с заданным регулярным выражением: r"\d+\.\d+"
# в строке: text
# и возвращает их в виде списка строк.


